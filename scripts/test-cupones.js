'use strict';
const fs=require('node:fs'),vm=require('node:vm');
const registered=[],actions={},state={promotions:[{id:1,name:'Cliente frecuente',code:'CLIENTE10',percent:10,enabled:true}],sales:[]};
let applied=0,logged='';
const document={getElementById:function(id){return id==='saineiCouponCode'?{value:' cliente10 '}:null;}};
const window={SAINEI_POS_MODULES:[]};
vm.runInNewContext(fs.readFileSync('sainei-mod-promociones.js','utf8'),{window,document,Date,Number,String,Math});
vm.runInNewContext(fs.readFileSync('sainei-mod-cupones.js','utf8'),{window,document,Date,Number,String,Math});
const api={state:()=>state,user:()=>({role:'admin'}),isAdmin:()=>true,addTab:x=>registered.push(x),addAction:(k,v)=>actions[k]=v,escape:String,money:String,number:Number,round3:Number,newId:()=>2,log:x=>logged=x,toast:()=>{},save:()=>Promise.resolve(true),refresh:()=>{},maxDiscount:()=>10,applyDiscount:p=>{applied=p;return p<=10;}};
window.SAINEI_POS_MODULES.forEach(x=>x.init(api));
if(!registered.some(x=>x.id==='promociones')||!registered.some(x=>x.id==='cupones'))throw Error('No se registraron ambas pestañas.');
if(typeof actions['saineiCouponApply']!=='function')throw Error('No se registró la acción de aplicar cupón.');
actions['saineiCouponApply']();
if(applied!==10||!logged.includes('CLIENTE10'))throw Error('El cupón vigente no aplicó el descuento autorizado.');
applied=0;document.getElementById=()=>({value:'NOEXISTE'});
actions['saineiCouponApply']();
if(applied!==0)throw Error('Se aplicó un cupón inexistente.');
state.promotions[0].enabled=false;document.getElementById=()=>({value:'CLIENTE10'});
actions['saineiCouponApply']();
if(applied!==0)throw Error('Se aplicó un cupón desactivado.');
console.log('OK: cupón vigente, inexistente y desactivado verificados.');

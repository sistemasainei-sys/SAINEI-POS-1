'use strict';
const fs = require('node:fs');
const assert = require('node:assert/strict');
const server = fs.readFileSync('server.js', 'utf8');
const index = fs.readFileSync('index.html', 'utf8');
assert.doesNotMatch(server, /LICENSE_PUBLIC_KEY|licenseToken|crypto\.verify\('RSA-SHA256'/);
assert.doesNotMatch(server, /!licenseState\(\)\.active/);
assert.match(server, /function licenseState\(\) \{ return \{ active: true, required: false/);
assert.doesNotMatch(index, /showLicenseScreen|licenseActivate|ACTIVAR SAINEI POS/);
assert.match(server, /if \(p === '\/api\/setup' && m === 'POST'\)/);
assert.match(server, /if \(p === '\/api\/login' && m === 'POST'\)/);
console.log('OK: instalación y operación sin licencia; el acceso sigue protegido por usuarios y PIN.');
